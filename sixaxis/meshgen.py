"""程式化產生旋轉體 (lathe) OBJ 網格：圓角外殼、微凸端蓋、細分管件。

網格以 z 為對稱軸、中心在原點；輪廓 (r, z) 依序由底部中心 → 外緣 → 頂部中心，
法向量由輪廓切線 (dr, dz) 求得外法向 (dz, -dr)，同一 smooth group 內平滑著色，
group 之間複製頂點形成銳邊。
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

N_THETA = 48


def _arc(cr, cz, rad, a0, a1, n=8):
    a = np.linspace(a0, a1, n)
    return [(cr + rad * np.cos(t), cz + rad * np.sin(t)) for t in a]


def _line(p0, p1, n):
    return [(p0[0] + (p1[0] - p0[0]) * s, p0[1] + (p1[1] - p0[1]) * s) for s in np.linspace(0, 1, n)]


def _dedup(pts):
    out = [pts[0]]
    for p in pts[1:]:
        if abs(p[0] - out[-1][0]) + abs(p[1] - out[-1][1]) > 1e-9:
            out.append(p)
    return out


def housing_profile(h: float, r: float, fillet_ratio: float = 0.22):
    """圓角圓柱（關節外殼）：單一 smooth group。"""
    f = fillet_ratio * r
    z0, z1 = -h / 2, h / 2
    pts = _line((0, z0), (r - f, z0), 4)
    pts += _arc(r - f, z0 + f, f, -np.pi / 2, 0, 8)
    pts += _line((r, z0 + f), (r, z1 - f), 10)
    pts += _arc(r - f, z1 - f, f, 0, np.pi / 2, 8)
    pts += _line((r - f, z1), (0, z1), 4)
    return [_dedup(pts)]


def tube_profile(length: float, r: float):
    """管件：側面沿長度細分（避免長三角形造成光照帶狀瑕疵），兩端銳邊。"""
    z0, z1 = -length / 2, length / 2
    return [
        _line((0, z0), (r, z0), 3),
        _line((r, z0), (r, z1), 24),
        _line((r, z1), (0, z1), 3),
    ]


def cap_profile(t: float, r: float):
    """端蓋：平底（藏在外殼內）+ 圓角外緣 + 微凸面。"""
    f = min(0.45 * t, 0.25 * r)
    dome = 0.35 * t
    side = _line((r, -t / 2), (r, t / 2 - f - dome), 3)
    side += _arc(r - f, t / 2 - f - dome, f, 0, np.pi / 2, 6)
    rr = np.linspace(r - f, 0, 8)
    zt = t / 2 - dome + dome * (1 - (rr / (r - f)) ** 2)  # 拋物面微凸
    side += list(zip(rr, zt))
    return [_line((0, -t / 2), (r, -t / 2), 3), _dedup(side)]


def ring_profile(t: float, r: float):
    f = 0.35 * t
    pts = _line((0, -t / 2), (r - f, -t / 2), 3)
    pts += _arc(r - f, -t / 2 + f, f, -np.pi / 2, 0, 5)
    pts += _arc(r - f, t / 2 - f, f, 0, np.pi / 2, 5)
    pts += _line((r - f, t / 2), (0, t / 2), 3)
    return [_dedup(pts)]


def lathe_obj(groups, n_theta: int = N_THETA) -> str:
    th = np.linspace(0, 2 * np.pi, n_theta, endpoint=False)
    ct, st = np.cos(th), np.sin(th)
    V, N, F = [], [], []
    for g in groups:
        g = np.asarray(g, float)
        # 輪廓法向（中央差分）
        d = np.zeros_like(g)
        d[1:-1] = g[2:] - g[:-2]
        d[0] = g[1] - g[0]
        d[-1] = g[-1] - g[-2]
        nrm = np.stack([d[:, 1], -d[:, 0]], 1)
        nrm /= np.linalg.norm(nrm, axis=1, keepdims=True)
        base = len(V)
        for (r, z), (nr, nz) in zip(g, nrm):
            for c, s in zip(ct, st):
                V.append((r * c, r * s, z))
                N.append((nr * c, nr * s, nz))
        for k in range(len(g) - 1):
            for j in range(n_theta):
                j2 = (j + 1) % n_theta
                a = base + k * n_theta + j
                b = base + k * n_theta + j2
                c_ = base + (k + 1) * n_theta + j2
                d_ = base + (k + 1) * n_theta + j
                F.append((a, b, c_))
                F.append((a, c_, d_))
    lines = ["# generated by sixaxis.meshgen"]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in V]
    lines += [f"vn {x:.5f} {y:.5f} {z:.5f}" for x, y, z in N]
    lines += [f"f {a + 1}//{a + 1} {b + 1}//{b + 1} {c + 1}//{c + 1}" for a, b, c in F]
    return "\n".join(lines) + "\n"


PROFILES = {"housing": housing_profile, "tube": tube_profile, "cap": cap_profile, "ring": ring_profile}


def mesh_name(kind: str, length: float, radius: float) -> str:
    return f"{kind}_L{round(length * 1e4):04d}_R{round(radius * 1e4):04d}.obj"


def write_mesh(directory: Path, kind: str, length: float, radius: float) -> str:
    name = mesh_name(kind, length, radius)
    path = Path(directory) / name
    path.parent.mkdir(parents=True, exist_ok=True)
    text = lathe_obj(PROFILES[kind](length, radius))
    if not path.exists() or path.read_text() != text:
        path.write_text(text)
    return name
